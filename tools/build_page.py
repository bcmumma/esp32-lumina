"""Build the S3 controller page from src/sender/web/index.html.

    python tools/build_page.py                 # regenerate src/sender/web/IndexHtml.cpp
    python tools/build_page.py --demo OUT.html # also write a demo page with a simulated API

Edit index.html, never IndexHtml.cpp. The demo strips the document wrapper (the Artifact
viewer adds its own) and injects tools/page_demo_mock.js in front of the page script.
"""
import argparse
import pathlib
import re

ROOT = pathlib.Path(__file__).resolve().parents[1]
SRC = ROOT / "src/sender/web/index.html"
CPP = ROOT / "src/sender/web/IndexHtml.cpp"
MOCK = ROOT / "tools/page_demo_mock.js"
DELIM = "rawliteral"


def build_cpp(html):
    if f'){DELIM}"' in html:
        raise SystemExit("index.html contains the raw-string delimiter")
    return (
        "// GENERATED by tools/build_page.py from index.html. Edit index.html, then rerun the script.\n"
        '#include "IndexHtml.h"\n#include <Arduino.h>\n\n'
        f'const char INDEX_HTML[] PROGMEM = R"{DELIM}(\n{html}){DELIM}";\n'
    )


def build_demo(html):
    body = html
    for pat in [r"<!doctype html>\s*", r"<html[^>]*>\s*", r"</html>\s*", r"<head>\s*", r"</head>\s*", r"<body>\s*", r"</body>\s*",
                r'<meta charset="utf-8">\s*', r'<meta name="viewport"[^>]*>\s*']:
        body = re.sub(pat, "", body, flags=re.I)
    mock = MOCK.read_text(encoding="utf-8")
    i = body.rfind("<script>")
    return body[:i] + f"<script>\n{mock}</script>\n" + body[i:]


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--demo")
    a = ap.parse_args()
    html = SRC.read_text(encoding="utf-8")
    CPP.write_text(build_cpp(html), encoding="utf-8", newline="\n")
    print(f"wrote {CPP.relative_to(ROOT)} ({len(html.encode())} bytes of page)")
    if a.demo:
        pathlib.Path(a.demo).write_text(build_demo(html), encoding="utf-8")
        print(f"wrote {a.demo}")


if __name__ == "__main__":
    main()
